#!/usr/bin/env node
// Generates the synthetic route modules used by the "bundle" fix. They are real modules, so Vite
// emits real chunks; their sizes mirror the ~85% initial-bundle cut from production.
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'demos');
const CHUNKS = {
  core: 70,
  'routes/graph': 150,
  'routes/search': 95,
  'routes/settings': 70,
  'routes/reports': 100,
  'routes/admin': 60,
};

let seed = 1;
const hex = () => {
  let out = '';
  for (let i = 0; i < 4; i++) {
    seed = (seed * 48271) % 2147483647;
    out += seed.toString(16).padStart(8, '0');
  }
  return out;
};

for (const [name, kb] of Object.entries(CHUNKS)) {
  const rows = [];
  let size = 0;
  while (size < kb * 1024) {
    const row = `"${hex()}"`;
    rows.push(row);
    size += row.length + 1;
  }
  const source = `// Generated by scripts/generate-demo-chunks.mjs. Synthetic payload, sized to mirror production.
const table: readonly string[] = [${rows.join(',')}];

/** Returns the payload size so callers keep the whole module (it cannot be tree-shaken away). */
export function size(): number {
  return table.reduce((total, row) => total + row.length, 0);
}
`;
  const file = join(root, `${name}.ts`);
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, source);
  console.log(`wrote src/demos/${name}.ts (~${kb} KB)`);
}
